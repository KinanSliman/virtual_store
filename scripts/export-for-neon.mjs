/**
 * Writes neon-setup.sql: the full schema plus every row from a local database,
 * as one script you can paste into Neon's SQL Editor.
 *
 * Useful when the machine can't open a direct Postgres connection (port 5432
 * blocked), which stops drizzle-kit from running migrations remotely.
 *
 *   node scripts/export-for-neon.mjs "postgres://user:pass@localhost:5432/virtual_store"
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { Client } from "pg";

const source = process.argv[2];
if (!source) {
  console.error(
    'Usage: node scripts/export-for-neon.mjs "<local postgres url>"',
  );
  process.exit(1);
}

// Order matters: parents before the rows that reference them.
const TABLES = [
  "categories",
  "products",
  "orders",
  "order_items",
  "product_views",
  "store_settings",
  "images",
];

function literal(value) {
  if (value === null) return "NULL";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  if (value instanceof Date) return `'${value.toISOString()}'`;
  if (Buffer.isBuffer(value)) return `decode('${value.toString("hex")}','hex')`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

const client = new Client({ connectionString: source });
await client.connect();

const parts = [];
parts.push("-- Generated by scripts/export-for-neon.mjs");
parts.push("-- Paste into the Neon SQL Editor to set up the database.\n");

// ---- schema, from the drizzle migrations -------------------------------
const migrationsDir = "drizzle";
const files = (await readdir(migrationsDir))
  .filter((f) => f.endsWith(".sql"))
  .sort();
parts.push("-- ===== schema =====");
for (const file of files) {
  const sql = await readFile(path.join(migrationsDir, file), "utf8");
  parts.push(`-- ${file}`);
  // drizzle separates statements with a marker comment
  parts.push(sql.split("--> statement-breakpoint").join("").trim());
}

// ---- data ---------------------------------------------------------------
parts.push("\n-- ===== data =====");
for (const table of TABLES) {
  const { rows, fields } = await client.query(`SELECT * FROM "${table}"`);
  if (rows.length === 0) continue;
  const columns = fields.map((f) => `"${f.name}"`).join(", ");
  parts.push(`\n-- ${table}: ${rows.length} row(s)`);
  for (const row of rows) {
    const values = fields.map((f) => literal(row[f.name])).join(", ");
    parts.push(`INSERT INTO "${table}" (${columns}) VALUES (${values});`);
  }
}

// ---- keep auto-increment ids in step with the imported rows -------------
parts.push("\n-- ===== sequences =====");
for (const table of ["categories", "products", "orders", "order_items", "product_views"]) {
  parts.push(
    `SELECT setval(pg_get_serial_sequence('${table}', 'id'), ` +
      `COALESCE((SELECT MAX(id) FROM "${table}"), 1), true);`,
  );
}

await writeFile("neon-setup.sql", parts.join("\n") + "\n", "utf8");
const { rows } = await client.query("SELECT 1");
if (rows.length) console.log("wrote neon-setup.sql");
await client.end();
